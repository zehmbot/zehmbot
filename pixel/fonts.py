class Font:
    def __init__(self, glyphs, cap, line, upper_only=False, fallback="?"):
        self.glyphs = {k: _g(v) for k, v in glyphs.items()}
        self.cap = cap
        self.line = line
        self.upper_only = upper_only
        self.fallback = fallback

    def normalize(self, text):
        text = text.replace("…", "...").replace("—", "-").replace("–", "-")
        text = text.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
        out = []
        for ch in text:
            if ch in self.glyphs or (self.upper_only and ch.upper() in self.glyphs):
                out.append(ch.upper() if self.upper_only else ch)
                continue
            base = unicodedata.normalize("NFKD", ch).encode("ascii", "ignore").decode()
            if base:
                out.append(base.upper() if self.upper_only else base)
            else:
                out.append(self.fallback)
        return "".join(out)

    def glyph(self, ch):
        if self.upper_only:
            ch = ch.upper()
        return self.glyphs.get(ch) or self.glyphs[self.fallback]

    def width(self, text, spacing=1):
        text = self.normalize(text)
        if not text:
            return 0
        return sum(len(self.glyph(c)[0]) for c in text) + spacing * (len(text) - 1)

    def truncate(self, text, max_w, spacing=1):
        text = self.normalize(text)
        if self.width(text, spacing) <= max_w:
            return text
        while text and self.width(text + "...", spacing) > max_w:
            text = text[:-1]
        return text.rstrip() + "..."

    def wrap(self, text, max_w, max_lines=None, spacing=1):
        words = self.normalize(text).split()
        lines, cur = [], ""
        for w in words:
            trial = f"{cur} {w}".strip()
            if self.width(trial, spacing) <= max_w:
                cur = trial
            else:
                if cur:
                    lines.append(cur)
                cur = w if self.width(w, spacing) <= max_w else self.truncate(w, max_w, spacing)
        if cur:
            lines.append(cur)
        if max_lines and len(lines) > max_lines:
            lines = lines[:max_lines]
            lines[-1] = self.truncate(lines[-1] + " ...", max_w, spacing)
        return lines


